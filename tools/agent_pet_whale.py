#!/usr/bin/env python3
"""Generate the Agent Pet whale as an LVGL 9 RGB565A8 image (original artwork).

Run: python tools/agent_pet_whale.py [--check] [--png out.png]
Requires Pillow 12.3.0 (same pin as tools/agent_pet_font.py). The eye is not
part of the bitmap: the firmware draws it as two small shapes so it can blink.
"""
import argparse
from pathlib import Path
import PIL
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'main/pet_whale_img.c'
BIG_TARGET = ROOT / 'main/pet_whale_big_img.c'  # 2x for desk mode
W, H, S = 112, 72, 8          # output size and supersampling factor
BODY = (77, 107, 254)         # brand-like blue
BACK = (61, 88, 235)
BELLY = (214, 223, 255)
FIN = (52, 76, 214)
LINE = (38, 58, 170)
EYE = (33, 37)                # eye centre in output pixels, used by main.c


def p(x, y):
    return (round(x * S), round(y * S))


def bezier(points, steps=40):
    """Cubic Bezier through 4 control points, in output-pixel units."""
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = points
    out = []
    for i in range(steps + 1):
        t = i / steps
        a, b, c, d = (1-t)**3, 3*(1-t)**2*t, 3*(1-t)*t**2, t**3
        out.append((a*x0 + b*x1 + c*x2 + d*x3, a*y0 + b*y1 + c*y2 + d*y3))
    return out


def outline():
    """Closed whale silhouette: round head, tapering body, tail rising right."""
    path = []
    path += bezier([(6, 44), (4, 22), (24, 14), (44, 16)])        # forehead
    path += bezier([(44, 16), (64, 18), (74, 28), (86, 26)])      # back to tail stem
    path += bezier([(86, 26), (91, 24), (93, 20), (93, 16)])      # stem rising
    path += bezier([(93, 16), (88, 13), (83, 9), (81, 3)])        # left fluke, inner edge
    path += bezier([(81, 3), (88, 4), (93, 8), (96, 12)])         # left fluke, outer edge
    path += bezier([(96, 12), (99, 7), (104, 3), (110, 2)])       # right fluke, outer edge
    path += bezier([(110, 2), (109, 10), (104, 15), (98, 18)])    # right fluke, inner edge
    path += bezier([(98, 18), (97, 32), (86, 44), (72, 52)])      # stem underside
    path += bezier([(72, 52), (58, 62), (30, 66), (16, 60)])      # belly
    path += bezier([(16, 60), (9, 57), (6, 51), (6, 44)])         # chin
    return [p(x, y) for x, y in path]


def render(scale=1):
    big = (W * S, H * S)
    mask = Image.new('L', big, 0)
    ImageDraw.Draw(mask).polygon(outline(), fill=255)
    color = Image.new('RGB', big, BODY)
    draw = ImageDraw.Draw(color)
    # Darker back band, softened so it reads as shading, not a stripe.
    back = Image.new('L', big, 0)
    ImageDraw.Draw(back).ellipse([p(4, -10), p(96, 30)], fill=255)
    back = back.filter(ImageFilter.GaussianBlur(4 * S))
    color = Image.composite(Image.new('RGB', big, BACK), color, back)
    draw = ImageDraw.Draw(color)
    # Pale belly following the lower curve.
    belly = Image.new('L', big, 0)
    ImageDraw.Draw(belly).ellipse([p(2, 48), p(64, 80)], fill=255)
    belly = belly.filter(ImageFilter.GaussianBlur(S))
    color = Image.composite(Image.new('RGB', big, BELLY), color, belly)
    draw = ImageDraw.Draw(color)
    # Belly grooves.
    for dy in (55, 59):
        draw.line(bezier_px([(16, dy), (28, dy + 3), (42, dy + 3), (54, dy - 1)]), fill=(186, 199, 255), width=S)
    # Small pectoral fin.
    draw.polygon(bezier_px([(44, 50), (52, 52), (58, 58), (60, 62)]) + bezier_px([(60, 62), (52, 62), (46, 58), (44, 50)]), fill=FIN)
    # Smile.
    draw.line(bezier_px([(12, 46), (16, 49), (21, 49), (25, 47)]), fill=LINE, width=S + S // 2)
    # Cheek.
    draw.ellipse([p(26, 43), p(32, 47)], fill=(255, 168, 196))
    image = Image.merge('RGBA', (*color.split(), mask))
    return image.resize((W * scale, H * scale), Image.LANCZOS)


def bezier_px(points):
    return [p(x, y) for x, y in bezier(points, 30)]


def to_c(image, symbol='pet_whale_img'):
    rgb, alpha = [], []
    for r, g, b, a in image.get_flattened_data():
        if a == 0:
            r = g = b = 0
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        rgb += [value & 0xFF, value >> 8]
        alpha.append(a)
    data = rgb + alpha
    w, h = image.size
    rows = ''.join('    ' + ', '.join(f'0x{v:02x}' for v in data[i:i+16]) + ',\n' for i in range(0, len(data), 16))
    return f'''/* Generated by tools/agent_pet_whale.py. Original Agent Pet whale artwork. */
#include "pet_whale_img.h"

static const uint8_t {symbol}_map[] = {{
{rows}}};

const lv_image_dsc_t {symbol} = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8,
               .w = {w}, .h = {h}, .stride = {w * 2}}},
    .data_size = sizeof({symbol}_map),
    .data = {symbol}_map,
}};
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--png', type=Path)
    args = parser.parse_args()
    assert PIL.__version__ == '12.3.0', 'Use Pillow 12.3.0 for reproducible output'
    image = render()
    if args.png:
        image.save(args.png)
    text = to_c(image)
    big = to_c(render(2), 'pet_whale_big_img')
    if args.check:
        assert TARGET.read_text() == text, 'pet_whale_img.c differs; regenerate'
        assert BIG_TARGET.read_text() == big, 'pet_whale_big_img.c differs; regenerate'
    else:
        TARGET.write_text(text)
        BIG_TARGET.write_text(big)
    print(f'whale {W}x{H} RGB565A8, {W * H * 3} bytes, eye at {EYE}')


if __name__ == '__main__':
    main()
