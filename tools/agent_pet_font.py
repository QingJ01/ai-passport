#!/usr/bin/env python3
"""Generate/check Agent Pet's OFL Noto SC font. Requires Pillow 12.3.0/FreeType 2.14.3.
Run from any directory: python tools/agent_pet_font.py [--check].
Input source is preserved under assets/fonts/agent-pet/source; see provenance.json.
"""
import argparse
import bisect
import hashlib
import json
from pathlib import Path
import re
import struct
from PIL import ImageFont, features
import PIL

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/fonts/agent-pet'
SOURCE = OUT / 'source/NotoSansSC-wght.ttf'
SHA256 = 'a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da'


def inventory():
    result = set(range(32, 127))
    for lead in range(0xa1, 0xf8):
        for trail in range(0xa1, 0xff):
            try:
                result.add(ord(bytes([lead, trail]).decode('gb2312')))
            except UnicodeDecodeError:
                pass
    return sorted(result)


def source_coverage(data):
    """Read actual nonzero glyph IDs from sfnt Unicode format-12 cmap."""
    count = struct.unpack_from('>H', data, 4)[0]
    tables = {data[12+i*16:16+i*16]: struct.unpack_from('>II', data, 20+i*16)
              for i in range(count)}
    offset = tables[b'cmap'][0]
    n = struct.unpack_from('>H', data, offset+2)[0]
    for i in range(n):
        platform, encoding, relative = struct.unpack_from('>HHI', data, offset+4+i*8)
        start = offset+relative
        if platform == 3 and encoding == 10 and struct.unpack_from('>H', data, start)[0] == 12:
            groups = struct.unpack_from('>I', data, start+12)[0]
            supported = set()
            for j in range(groups):
                first, last, gid = struct.unpack_from('>III', data, start+16+j*12)
                supported.update(cp for cp in range(first, last+1) if gid+cp-first)
            return supported
    raise RuntimeError('No Windows Unicode format-12 source cmap')


def raster(font, cp):
    mask, (left, top) = font.getmask2(chr(cp), mode='L', anchor='ls')
    w, h = mask.size
    pixels = [(value * 3 + 127) // 255 for value in mask]
    # True blank glyphs retain their advance, with zero area and no bitmap bytes.
    if not any(pixels):
        left = top = w = h = 0
        pixels = []
    advance = int(font.getlength(chr(cp)) * 16 + 0.5)
    return (advance, w, h, left, -top-h), pixels


def packed(pixels):
    result = bytearray((len(pixels)+3)//4)
    for i, value in enumerate(pixels):
        result[i//4] |= value << (6-2*(i%4))
    return result


def array(name, ctype, values, width=16):
    return 'static const '+ctype+' '+name+'[] = {\n'+''.join(
        '    '+', '.join(str(x) for x in values[i:i+width])+',\n'
        for i in range(0, len(values), width))+'};\n'


def generate(font, cps):
    bitmap = bytearray()
    desc = [(0, 0, 0, 0, 0, 0)]
    for cp in cps:
        metrics, pixels = raster(font, cp)
        desc.append((len(bitmap),)+metrics)
        bitmap.extend(packed(pixels))
    assert len(bitmap) < (1 << 20), 'LV_FONT_FMT_TXT_LARGE=0 overflow'
    ascent = max(d[3]+d[5] for d in desc)
    descent = max(-d[5] for d in desc)
    line_height = ascent+descent
    sparse = cps[95:]
    text = '/* Generated by tools/agent_pet_font.py; Noto Sans SC, SIL OFL 1.1. See OFL.txt. */\n#include "pet_font_cjk_16.h"\n\n'
    text += array('glyph_bitmap', 'uint8_t', bitmap)
    text += '\nstatic const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n'
    for d in desc:
        text += '    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},\n' % d
    text += '};\n\n'+array('unicode_list', 'uint16_t', [cp-sparse[0] for cp in sparse])
    text += '''\nstatic const lv_font_fmt_txt_cmap_t cmaps[] = {
    {.range_start = 32, .range_length = 95, .glyph_id_start = 1,
     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},
    {.range_start = %d, .range_length = %d, .glyph_id_start = 96,
     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = %d,
     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}
};
static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 2, .bpp = 2,
    .kern_classes = 0, .bitmap_format = LV_FONT_FMT_TXT_PLAIN, .stride = 0
};
const lv_font_t pet_font_cjk_16 = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = %d, .base_line = %d,
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2, .underline_thickness = 1,
    .dsc = &font_dsc, .fallback = NULL, .user_data = NULL
};
''' % (sparse[0], sparse[-1]-sparse[0]+1, len(sparse), line_height, descent)
    stats = {'glyphs':len(cps), 'han_glyphs':sum(0x4e00 <= c <= 0x9fff for c in cps),
             'bitmap_bytes':len(bitmap), 'glyph_descriptor_bytes_small':len(desc)*8,
             'unicode_list_bytes':len(sparse)*2, 'line_height':line_height, 'base_line':descent,
             'max_box_width':max(d[2] for d in desc), 'max_box_height':max(d[3] for d in desc)}
    return text, stats


def validate(text, font, cps):
    """Parse emitted C, independently decode every bit and cmap, compare FreeType."""
    def numbers(name):
        body = re.search(r'\b'+name+r'\[\] = \{(.*?)\};',text,re.S).group(1)
        return [int(x) for x in re.findall(r'\d+', body)]
    bitmap = numbers('glyph_bitmap')
    sparse = numbers('unicode_list')
    rows = re.findall(r'\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}', text)
    desc = [tuple(map(int, row)) for row in rows]
    cmaps = re.findall(r'\.range_start = (\d+), \.range_length = (\d+), \.glyph_id_start = (\d+)',text)
    maps = [tuple(map(int, row)) for row in cmaps]
    def lookup(cp):
        for index, (start,length,gid) in enumerate(maps):
            if start <= cp < start+length:
                if index == 0:
                    return gid+cp-start
                offset = cp-start
                pos = bisect.bisect_left(sparse,offset)
                return gid+pos if pos < len(sparse) and sparse[pos] == offset else 0
        return 0
    assert len(desc) == len(cps)+1 and desc[0] == (0,0,0,0,0,0)
    for cp in cps:
        gid = lookup(cp)
        assert gid, f'Missing U+{cp:04X}'
        offset, *metrics = desc[gid]
        expected_metrics, expected_pixels = raster(font,cp)
        assert tuple(metrics) == expected_metrics, f'Metrics U+{cp:04X}'
        count = metrics[1]*metrics[2]
        assert offset+(count+3)//4 <= len(bitmap)
        decoded = [(bitmap[offset+i//4] >> (6-2*(i%4))) & 3 for i in range(count)]
        assert decoded == expected_pixels, f'Bitmap U+{cp:04X}'
    for missing in (0, 31, 0x9f98, 0x20000, 0x1f600):
        assert not lookup(missing), f'Negative coverage U+{missing:04X}'
    print(f'PASS: {len(cps)} cmap lookups, all glyph metrics and pixels, 5 negative cases')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assert PIL.__version__ == '12.3.0', 'Use Pillow 12.3.0 for reproducible rasterization'
    assert features.version('freetype2') == '2.14.3', 'Use FreeType 2.14.3'
    data = SOURCE.read_bytes()
    assert hashlib.sha256(data).hexdigest() == SHA256, 'Source font checksum mismatch'
    cps = inventory()
    missing = set(cps)-source_coverage(data)
    assert not missing, f'Source missing {sorted(missing)}'
    font = ImageFont.truetype(str(SOURCE),16)
    font.set_variation_by_axes([400])
    text, stats = generate(font,cps)
    target = OUT/'pet_font_cjk_16.c'
    inventory_text = ''.join(f'U+{cp:04X}\n' for cp in cps)
    if args.check:
        assert target.read_text() == text, 'Generated C differs; regenerate'
        assert (OUT/'coverage.txt').read_text() == inventory_text
    else:
        target.write_text(text)
        (OUT/'coverage.txt').write_text(inventory_text)
        (OUT/'metrics.json').write_text(json.dumps(stats,indent=2)+'\n')
    validate(target.read_text(),font,cps)
    print(json.dumps(stats,indent=2))

if __name__ == '__main__':
    main()
