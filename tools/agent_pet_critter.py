#!/usr/bin/env python3
"""Generate the Claude Code theme pet: an original pixel critter (LVGL 9 RGB565A8).

Run: python tools/agent_pet_critter.py [--check]
Pure Python, no dependencies. Each grid cell becomes SCALE x SCALE pixels so the
art stays crisp. The eyes are drawn by main.c (PET_CRITTER_EYE_*) so they blink.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'main/pet_critter_img.c'
BIG_TARGET = ROOT / 'main/pet_critter_big_img.c'  # 2x for desk mode
SCALE = 4
PALETTE = {
    '.': None,
    'o': (217, 119, 87),    # terracotta body
    'd': (184, 92, 63),     # shade on the right and bottom
    'l': (240, 178, 150),   # highlight
    'p': (240, 160, 140),   # cheeks
    'k': (60, 40, 36),      # mouth
    'a': (184, 92, 63),     # antenna stalk
    's': (245, 196, 122),   # antenna star
}
GRID = [
    "..........s.........",
    ".........sss........",
    "..........s.........",
    "..........a.........",
    ".....oooooooooo.....",
    "...oooooooooooooo...",
    "..oolloooooooooood..",
    "..ollooooooooooood..",
    ".oooooooooooooooood.",
    ".oooooooooooooooood.",
    ".oooooooooooooooood.",
    ".oppoooooooooooppod.",
    ".ooooooookkoooooood.",
    ".oooooooooooooooodd.",
    "..ooooooooooooooddd.",
    "...dddddddddddddd...",
    "....ddd......ddd....",
    "....ddd......ddd....",
]
# Eye cells (column, row) of the top-left of each 2x3-cell eye, used by main.c.
EYES = ((5, 8), (12, 8))


def to_c(scale=SCALE, symbol='pet_critter_img'):
    assert all(len(row) == len(GRID[0]) for row in GRID), 'ragged grid'
    w, h = len(GRID[0]) * scale, len(GRID) * scale
    rgb, alpha = [], []
    for row in GRID:
        line_rgb, line_alpha = [], []
        for cell in row:
            color = PALETTE[cell]
            r, g, b = color or (0, 0, 0)
            value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            line_rgb += [value & 0xFF, value >> 8] * scale
            line_alpha += [255 if color else 0] * scale
        rgb += line_rgb * scale
        alpha += line_alpha * scale
    data = rgb + alpha
    rows = ''.join('    ' + ', '.join(f'0x{v:02x}' for v in data[i:i+16]) + ',\n' for i in range(0, len(data), 16))
    return w, h, f'''/* Generated by tools/agent_pet_critter.py. Original Agent Pet pixel critter. */
#include "pet_critter_img.h"

static const uint8_t {symbol}_map[] = {{
{rows}}};

const lv_image_dsc_t {symbol} = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8,
               .w = {w}, .h = {h}, .stride = {w * 2}}},
    .data_size = sizeof({symbol}_map),
    .data = {symbol}_map,
}};
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    w, h, text = to_c()
    _, _, big = to_c(SCALE * 2, 'pet_critter_big_img')
    if args.check:
        assert TARGET.read_text() == text, 'pet_critter_img.c differs; regenerate'
        assert BIG_TARGET.read_text() == big, 'pet_critter_big_img.c differs; regenerate'
    else:
        TARGET.write_text(text)
        BIG_TARGET.write_text(big)
    print(f'critter {w}x{h} RGB565A8, {w * h * 3} bytes, eyes at cells {EYES} x{SCALE}')


if __name__ == '__main__':
    main()
