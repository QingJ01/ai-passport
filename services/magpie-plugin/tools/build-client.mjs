import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('..', import.meta.url);
const sources = await Promise.all(['src/remote-definition.mjs', 'src/client-core.mjs'].map(async (path) => {
  const content = (await readFile(new URL(path, root), 'utf8')).replace(/^export /gm, '');
  if (/^\s*(import|export)\b/m.test(content)) throw new Error('client_sources_must_be_self_contained');
  return content;
}));
const output = `// Generated by tools/build-client.mjs. Do not edit this distributable directly.
window.__ModuleLoader__.load({
  id: '@ai-passport/dsh-agent-pet',
  factory: (require) => {
    const z = require('zod').z;
${sources.join('\n')}
    return {
      inject: ['remote', 'uiWorkspace'],
      async apply(ctx) {
        const unmount = await ctx.remote.$mount(navigationDefinition(z));
        const binding = ctx.inject(['remote.agentPetNavigation'], (clientCtx) => {
          const companion = startCompanion(clientCtx, { remote: clientCtx.remote.agentPetNavigation });
          return companion.stop;
        });
        return async () => { await binding.dispose(); await unmount(); };
      },
    };
  },
});
`;
const destination = new URL('src/client.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('client_bundle_stale');
} else await writeFile(destination, output);
